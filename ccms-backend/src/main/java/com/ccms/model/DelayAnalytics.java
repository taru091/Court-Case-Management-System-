package com.ccms.model;

public class DelayAnalytics {
    private int delayedCases;
    private double averageDelayDays;

    public int getDelayedCases() {
        return delayedCases;
    }

    public void setDelayedCases(int delayedCases) {
        this.delayedCases = delayedCases;
    }

    public double getAverageDelayDays() {
        return averageDelayDays;
    }

    public void setAverageDelayDays(double averageDelayDays) {
        this.averageDelayDays = averageDelayDays;
    }
}
